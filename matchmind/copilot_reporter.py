"""Match Report agent built on the GitHub Copilot SDK.

A Copilot session is given ONLY the read-only MatchMind MCP tools, researches
the match through them (state at any minute, key moments, grounded
explanations, player tags) and writes a post-match report in Markdown.
The report can be published as a GitHub Gist through the GitHub CLI.

  python -m matchmind.cli report --seed 7            # writes reports/match_7.md
  python -m matchmind.cli report --seed 7 --gist     # ...and publishes it with `gh gist create`

Needs a GitHub account with Copilot access (the SDK uses your `gh`/Copilot login).
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

MCP_TOOLS = ["get_match", "get_match_state", "list_moments", "explain_moment", "get_player_tag", "get_events"]

PROMPT = """You are MatchMind's Match Report agent. Match seed: {seed}. All data is SYNTHETIC.
Use the matchmind MCP tools to research the match: get_match first, then get_match_state at half-time (minute 45)
and full time, list_moments with min_importance 0.5, explain_moment for every goal, and get_player_tag for the two
best players. Then write a {words}-word post-match report in Markdown with:
- a headline and a one-line standfirst with the final score
- the story of the match in order, explaining WHY the key moments mattered, using only numbers the tools returned
- a "By the numbers" table (possession, xG, shots, pass accuracy, pressures) for both teams
- a "Player of the match" paragraph
End with: "_Generated by MatchMind from synthetic data._" Return only the Markdown."""


def mcp_config() -> dict:
    return {
        "type": "stdio",
        "command": sys.executable,
        "args": ["-m", "matchmind.mcp_server"],
        "tools": ["*"],
        "working_directory": str(Path(__file__).resolve().parent.parent),
    }


async def write_report(seed: int, model: str | None = None, words: int = 450, timeout: float = 240.0) -> str:
    from copilot import CopilotClient
    from copilot.session import PermissionHandler

    async with CopilotClient() as client:
        session = await client.create_session(
            on_permission_request=PermissionHandler.approve_all,  # safe: only read-only MatchMind tools are available
            model=model,
            mcp_servers={"matchmind": mcp_config()},
            available_tools=[f"mcp:matchmind-{t}" for t in MCP_TOOLS],
            name=f"matchmind-report-{seed}",
        )
        async with session:
            event = await session.send_and_wait(PROMPT.format(seed=seed, words=words), timeout=timeout)
    content = getattr(getattr(event, "data", None), "content", None)
    if not content:
        raise RuntimeError("Copilot returned no report")
    return content.strip()


def save_report(seed: int, markdown: str, out_dir: str = "reports") -> Path:
    path = Path(out_dir) / f"match_{seed}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(markdown + "\n")
    return path


def publish_gist(path: Path, public: bool = False) -> str:
    """Publish with the GitHub CLI and return the gist URL."""
    cmd = ["gh", "gist", "create", str(path), "--desc", f"MatchMind report: {path.stem} (synthetic data)"]
    if public:
        cmd.append("--public")
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout.strip()
